/** Preferred country key when several share a dial code. */
const PREFERRED_ABBR_BY_DIAL = {
    '+973': 'BH',
    '+1': 'US',
    '+7': 'RU',
};

/** Bahrain first (signup default), then A–Z by label. */
export const phoneCountryOptions = (() => {
    const bahrain = ALL_PHONE_COUNTRY_OPTIONS.find((option) => option.value === 'BH');
    const rest = ALL_PHONE_COUNTRY_OPTIONS.filter((option) => option.value !== 'BH').sort((a, b) =>
        a.label.localeCompare(b.label, undefined, { sensitivity: 'base' }),
    );

    return bahrain ? [bahrain, ...rest] : rest;
})();

/** Dial codes longest-first for E.164 parsing. */
export const phoneCountryCodes = [...new Set(phoneCountryOptions.map((option) => option.dial))].sort(
    (a, b) => b.length - a.length,
);

/**
 * @param {string} abbr
 * @returns {string}
 */
export function dialForCountryAbbr(abbr) {
    return phoneCountryOptions.find((option) => option.value === abbr)?.dial ?? '+973';
}

/**
 * @param {string} dial
 * @returns {string}
 */
export function preferredAbbrForDial(dial) {
    if (PREFERRED_ABBR_BY_DIAL[dial]) {
        return PREFERRED_ABBR_BY_DIAL[dial];
    }

    return phoneCountryOptions.find((option) => option.dial === dial)?.value ?? 'BH';
}
